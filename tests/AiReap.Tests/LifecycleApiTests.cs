    [Fact]
    public async Task Lifecycle_response_carries_stage_owner_checks_actions_gaps_and_history()
    {
        var projectId = await ProjectAsync();

        var (status, state) = await _ba.Api.GetAsync($"/api/projects/{projectId}/lifecycle");
        Assert.Equal(200, status);
        Assert.Equal(Draft, state!["status"]!.GetValue<int>());
        Assert.Equal("Draft", state["stageLabel"]!.GetValue<string>());
        Assert.Equal(Roles.BusinessAnalyst, state["ownerRole"]!.GetValue<string>());
        Assert.Equal(RequirementsGathering, state["nextStatus"]!.GetValue<int>());
        Assert.False(state["nextIsGated"]!.GetValue<bool>());
        Assert.True(state["readyToAdvance"]!.GetValue<bool>());
        Assert.Equal(4, state["exitChecks"]!.AsArray().Count);
        Assert.All(state["exitChecks"]!.AsArray(), c => Assert.True(c!["passed"]!.GetValue<bool>()));
        Assert.Null(state["pendingTransition"]);
        Assert.Empty(state["evidenceGaps"]!.AsArray());
        Assert.Single(state["history"]!.AsArray()); // the baseline row
        var actions = state["actions"]!;
        Assert.True(actions["canAdvance"]!.GetValue<bool>());
        Assert.False(actions["canSubmitForApproval"]!.GetValue<bool>());
        Assert.False(actions["canDecide"]!.GetValue<bool>());
        Assert.False(actions["canRollback"]!.GetValue<bool>());

        // Same project, another member's view: a Developer may not advance Draft.
        var (_, devState) = await _dev.Api.GetAsync($"/api/projects/{projectId}/lifecycle");
        Assert.False(devState!["actions"]!["canAdvance"]!.GetValue<bool>());

        // Non-members can't read it; unknown projects are not revealed either.
        var outsider = await _host.ActorAsync(Roles.BusinessAnalyst);
        Assert.Equal(403, (await outsider.Api.GetAsync($"/api/projects/{projectId}/lifecycle")).Status);
        Assert.Equal(403, (await outsider.Api.GetAsync($"/api/projects/{projectId}/lifecycle/history")).Status);
        Assert.Equal(404, (await _admin.Api.GetAsync($"/api/projects/{Guid.NewGuid()}/lifecycle")).Status);

        var (ps, policy) = await _qa.Api.GetAsync("/api/lifecycle/policy");
        Assert.Equal(200, ps);
        Assert.Equal(8, policy!.AsArray().Count);
        Assert.Equal(Roles.Developer, policy[Design]!["ownerRole"]!.GetValue<string>());
        Assert.True(policy[Design]!["leavingIsGated"]!.GetValue<bool>());
        Assert.Equal(Roles.Reviewer, policy[Design]!["gateApproverRole"]!.GetValue<string>());
    }

