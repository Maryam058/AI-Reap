        Assert.Equal(409, (await _admin.Api.SendAsync(HttpMethod.Patch, Path(incomplete), new { status = Design })).Status);
        Assert.Equal(Draft, await StatusAsync(incomplete));
        Assert.Equal(1, await _host.ScalarAsync($"SELECT COUNT(*) FROM ProjectStageTransitions WHERE ProjectId = '{incomplete}'"));

        // Staying put is still a harmless 200.
        Assert.Equal(200, (await _ba.Api.SendAsync(HttpMethod.Patch, Path(incomplete), new { status = Draft })).Status);

        // A legal move goes through the lifecycle and lands in its history.
        var complete = await ProjectAsync();
        var (s, moved) = await _ba.Api.SendAsync(HttpMethod.Patch, Path(complete), new { status = RequirementsGathering });
        Assert.Equal(200, s);
        Assert.Equal(RequirementsGathering, moved!["status"]!.GetValue<int>());
        Assert.Equal(1, await _host.ScalarAsync($"SELECT COUNT(*) FROM ProjectStageTransitions WHERE ProjectId = '{complete}' AND Kind = 1 AND State = 1"));
        Assert.Equal(409, (await _ba.Api.SendAsync(HttpMethod.Patch, Path(complete), new { status = Draft })).Status);

        // A gated stage only becomes a pending request: 202, status unchanged.
        var design = await ProjectInDesignAsync();
        var (gs, stillDesign) = await _dev.Api.SendAsync(HttpMethod.Patch, Path(design), new { status = Approved });
        Assert.Equal(202, gs);
        Assert.Equal(Design, stillDesign!["status"]!.GetValue<int>());
        Assert.Equal(Design, await StatusAsync(design));
        Assert.Equal(1, await _host.ScalarAsync($"SELECT COUNT(*) FROM ProjectStageTransitions WHERE ProjectId = '{design}' AND State = 0"));
        Assert.Equal(409, (await _dev.Api.SendAsync(HttpMethod.Patch, Path(design), new { status = Approved })).Status);
    }

