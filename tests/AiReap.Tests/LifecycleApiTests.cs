    private async Task<string> ProjectAsync(bool complete = true, params Actor[] members)
    {
        var (status, body) = await _ba.Api.PostAsync("/api/projects", new
        {
            name = "Leave system",
            businessProblem = "Paper forms",
            objectives = "Cut leave admin time",
            scope = complete ? "Employees and managers" : null
        });
        Assert.Equal(201, status);
        var id = Id(body);
        foreach (var member in members.Length > 0 ? members : [_dev, _reviewer, _reviewer2, _qa])
        {
            Assert.InRange((await _host.AddMemberAsync(_ba.Api, id, member.Api)).Status, 200, 201);
        }

        return id;
    }

    private Task SetStatusAsync(string projectId, int status) =>
        _host.ExecuteAsync($"UPDATE Projects SET Status = {status} WHERE Id = '{projectId}'");

    private Task<int> StatusAsync(string projectId) => _host.ScalarAsync($"SELECT Status FROM Projects WHERE Id = '{projectId}'");

    private Task<int> NotificationsAsync(string where) => _host.ScalarAsync($"SELECT COUNT(*) FROM ProjectNotifications WHERE {where}");

    private async Task<List<string>> ArtifactIdsAsync(string projectId, string types)
    {
        await using var conn = new SqlConnection(_host.ConnectionString);
        await conn.OpenAsync();
        await using var cmd = new SqlCommand($"SELECT Id FROM Artifacts WHERE ProjectId = '{projectId}' AND ArtifactType IN ({types})", conn);
        await using var reader = await cmd.ExecuteReaderAsync();
        var ids = new List<string>();
        while (await reader.ReadAsync()) ids.Add(reader.GetGuid(0).ToString());
        return ids;
    }

    // A project sitting in Design with every Design exit check passing: the manual chain is
    // generated by the stub AI, approved directly in SQL, and each design artifact gets a Developer
    // review through the real endpoint.
    private async Task<string> ProjectInDesignAsync(params Actor[] members)
    {
        var projectId = await ProjectAsync(true, members);
        var (_, source) = await _ba.Api.PostAsync($"/api/projects/{projectId}/requirement-sources",
            new { sourceType = 1, rawText = "Employees submit leave requests; managers approve them." });
        var sourceId = Id(source);
        Assert.Equal(200, (await _ba.Api.PostAsync($"/api/requirement-sources/{sourceId}/generate-requirements")).Status);
        var (_, stories) = await _ba.Api.PostAsync($"/api/requirement-sources/{sourceId}/generate-user-stories");
        foreach (var story in stories!.AsArray())
        {
            await _ba.Api.PostAsync($"/api/artifacts/{Id(story)}/generate-acceptance-criteria");
        }

        foreach (var step in new[] { "generate-design", "generate-data-entities", "generate-api-specs", "generate-tasks" })
        {
            Assert.Equal(200, (await _ba.Api.PostAsync($"/api/requirement-sources/{sourceId}/{step}")).Status);
        }

        await _host.ExecuteAsync($"UPDATE Artifacts SET Status = 3, ApprovedVersion = CurrentVersion WHERE ProjectId = '{projectId}'");
        var developer = members.Length == 0 || members.Contains(_dev) ? _dev : _admin;
        foreach (var id in await ArtifactIdsAsync(projectId, "6,7,8"))
        {
            // An Administrator's comment is not a Developer review; only projects with a developer get one.
            if (developer == _dev)
            {
                Assert.Equal(201, (await _dev.Api.PostAsync($"/api/artifacts/{id}/reviews", new { comment = "Reviewed." })).Status);
            }
        }

        await SetStatusAsync(projectId, Design);
        return projectId;
    }

    private async Task<JsonNode> SubmitDesignAsync(string projectId, Actor? by = null)
    {
        var (status, body) = await (by ?? _dev).Api.PostAsync($"/api/projects/{projectId}/lifecycle/transitions",
            new { targetStatus = Approved, note = "Design reviewed." });
        Assert.Equal(201, status);
        Assert.Equal(Pending, body!["state"]!.GetValue<int>());
        return body;
    }

    private static string Code(JsonNode? problem) => problem!["code"]!.GetValue<string>();

