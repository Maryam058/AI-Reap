    [Fact]
    public async Task Notifications_are_deduplicated_listed_per_user_and_acknowledged_once()
    {
        var projectId = await ProjectInDesignAsync();
        var transitionId = Guid.Parse(Id(await SubmitDesignAsync(projectId)));

        // Raising the same event again for the same transition adds nothing...
        using (var scope = _host.Factory.Services.CreateScope())
        {
            var db = scope.ServiceProvider.GetRequiredService<IAiReapDbContext>();
            var notifier = new LifecycleNotifications(db, scope.ServiceProvider.GetRequiredService<IUserRoleDirectory>());
            var project = await db.Projects.SingleAsync(p => p.Id == Guid.Parse(projectId));
            var transition = await db.ProjectStageTransitions.SingleAsync(t => t.Id == transitionId);
            await notifier.ApprovalRequestedAsync(project, transition, default);
            await db.SaveChangesAsync();
        }

        Assert.Equal(2, await NotificationsAsync($"TransitionId = '{transitionId}'"));

        // ...and the database refuses a duplicate outright.
        await Assert.ThrowsAsync<SqlException>(() => _host.ExecuteAsync($"""
            INSERT INTO ProjectNotifications (Id, ProjectId, TransitionId, RecipientUserId, Kind, Message, CreatedAt)
            VALUES (NEWID(), '{projectId}', '{transitionId}', '{_reviewer.Id}', {ApprovalRequested}, 'dup', GETUTCDATE())
            """));

        var (ls, list) = await _reviewer.Api.GetAsync("/api/notifications");
        Assert.Equal(200, ls);
        var notice = Assert.Single(list!.AsArray())!;
        Assert.Equal(ApprovalRequested, notice["kind"]!.GetValue<int>());
        Assert.Null(notice["acknowledgedAt"]);
        Assert.Empty((await _dev.Api.GetAsync("/api/notifications")).Body!.AsArray());

        // Someone else's notification is not revealed.
        Assert.Equal(404, (await _reviewer2.Api.PostAsync($"/api/notifications/{Id(notice)}/acknowledge")).Status);

        var (a1, first) = await _reviewer.Api.PostAsync($"/api/notifications/{Id(notice)}/acknowledge");
        Assert.Equal(200, a1);
        var at = first!["acknowledgedAt"]!.GetValue<DateTime>();
        var (a2, second) = await _reviewer.Api.PostAsync($"/api/notifications/{Id(notice)}/acknowledge");
        Assert.Equal(200, a2);
        Assert.Equal(at, second!["acknowledgedAt"]!.GetValue<DateTime>());

        Assert.Empty((await _reviewer.Api.GetAsync("/api/notifications")).Body!.AsArray());
        Assert.Single((await _reviewer.Api.GetAsync("/api/notifications?includeAcknowledged=true")).Body!.AsArray());
    }

    [Fact]
    public async Task Deciding_or_withdrawing_a_request_closes_its_approval_requests_only()
    {
        var projectId = await ProjectInDesignAsync();
        string Open(string transitionId, int kind) =>
            $"TransitionId = '{transitionId}' AND Kind = {kind} AND AcknowledgedAt IS NULL";

        // Rejected: nothing is left to approve; the requester's rejection notice stays unread.
        var rejected = Id(await SubmitDesignAsync(projectId));
        Assert.Equal(2, await NotificationsAsync(Open(rejected, ApprovalRequested)));
        Assert.Equal(200, (await _reviewer.Api.PostAsync($"/api/stage-transitions/{rejected}/decision", new { approve = false, reason = "Add error responses." })).Status);
        Assert.Equal(0, await NotificationsAsync(Open(rejected, ApprovalRequested)));
        Assert.Equal(2, await NotificationsAsync($"TransitionId = '{rejected}' AND Kind = {ApprovalRequested}")); // kept as history
        Assert.Equal(1, await NotificationsAsync(Open(rejected, TransitionRejected) + $" AND RecipientUserId = '{_dev.Id}'"));

        // Withdrawn: same.
        var withdrawn = Id(await SubmitDesignAsync(projectId));
        Assert.Equal(200, (await _dev.Api.PostAsync($"/api/stage-transitions/{withdrawn}/withdraw", new { note = "Not yet." })).Status);
        Assert.Equal(0, await NotificationsAsync(Open(withdrawn, ApprovalRequested)));

        // Approved: closed for every reviewer, not just the one who decided; the handover is new and unread.
        var approved = Id(await SubmitDesignAsync(projectId));
        Assert.Equal(200, (await _reviewer.Api.PostAsync($"/api/stage-transitions/{approved}/decision", new { approve = true })).Status);
        Assert.Equal(0, await NotificationsAsync(Open(approved, ApprovalRequested)));
        Assert.Equal(2, await NotificationsAsync(Open(approved, Handover)));
        Assert.DoesNotContain((await _reviewer2.Api.GetAsync("/api/notifications")).Body!.AsArray(), n => n!["kind"]!.GetValue<int>() == ApprovalRequested);
    }

