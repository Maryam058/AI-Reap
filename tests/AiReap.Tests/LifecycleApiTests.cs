    [Fact]
    public async Task Gated_submit_notifies_reviewers_and_a_different_reviewer_approves()
    {
        var projectId = await ProjectInDesignAsync();
        var pending = await SubmitDesignAsync(projectId);
        var id = Id(pending);
        Assert.Equal(Design, await StatusAsync(projectId));

        // Both reviewers on the project are asked, the submitting developer is not.
        Assert.Equal(1, await NotificationsAsync($"TransitionId = '{id}' AND Kind = {ApprovalRequested} AND RecipientUserId = '{_reviewer.Id}'"));
        Assert.Equal(1, await NotificationsAsync($"TransitionId = '{id}' AND Kind = {ApprovalRequested} AND RecipientUserId = '{_reviewer2.Id}'"));
        Assert.Equal(2, await NotificationsAsync($"TransitionId = '{id}'"));

        var (_, reviewerState) = await _reviewer.Api.GetAsync($"/api/projects/{projectId}/lifecycle");
        Assert.Equal(id, Id(reviewerState!["pendingTransition"]));
        Assert.True(reviewerState["actions"]!["canDecide"]!.GetValue<bool>());

        // Only Reviewer/Administrator may decide (static role gate -> 403), and never the requester.
        foreach (var actor in new[] { _dev, _qa, _ba })
        {
            Assert.Equal(403, (await actor.Api.PostAsync($"/api/stage-transitions/{id}/decision", new { approve = true })).Status);
        }

        var (as_, approved) = await _reviewer.Api.PostAsync($"/api/stage-transitions/{id}/decision", new { approve = true, reason = "Baseline approved." });
        Assert.Equal(200, as_);
        Assert.Equal(Done, approved!["state"]!.GetValue<int>());
        Assert.Equal(Roles.Reviewer, approved["decidedByRole"]!.GetValue<string>());
        Assert.Equal(Approved, await StatusAsync(projectId));

        // Handover to the Approved stage's owners: both Reviewers, the approver included.
        Assert.Equal(1, await NotificationsAsync($"TransitionId = '{id}' AND Kind = {Handover} AND RecipientUserId = '{_reviewer2.Id}'"));
        Assert.Equal(1, await NotificationsAsync($"TransitionId = '{id}' AND Kind = {Handover} AND RecipientUserId = '{_reviewer.Id}'"));
        Assert.Equal(0, await NotificationsAsync($"TransitionId = '{id}' AND Kind = {Handover} AND RecipientUserId = '{_dev.Id}'"));

        Assert.Equal(409, (await _reviewer2.Api.PostAsync($"/api/stage-transitions/{id}/decision", new { approve = true })).Status);
        Assert.Equal(404, (await _reviewer.Api.PostAsync($"/api/stage-transitions/{Guid.NewGuid()}/decision", new { approve = true })).Status);
    }

