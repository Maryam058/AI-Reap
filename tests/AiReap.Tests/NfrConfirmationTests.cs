using System.Globalization;
using System.Text.Json.Nodes;
using AiReap.Domain.Common;
using AiReap.Domain.Enums;
using Xunit;
using static AiReap.Tests.LifecycleTestSupport;

namespace AiReap.Tests;

// REAP-045 — confirming an NFR's proposed target (POST /api/artifacts/{id}/nfr-confirmation).
// Only a Business Analyst or Reviewer who did not author the NFR may confirm it; confirmation is
// requirement validation, separate from approval; and a normal edit can never manufacture or keep
// a confirmation for a changed target.
public class NfrConfirmationTests : IAsyncLifetime
{
    private const int AiGenerated = 0, UnderReview = 2, Approved = 3, Rejected = 4;
    private const string Confirmed = "confirmed", Proposed = "proposed_assumption";

    private readonly TestHost _host = new();
    private Actor _ba = null!, _ba2 = null!, _reviewer = null!, _dev = null!, _qa = null!, _admin = null!;

    public async Task InitializeAsync()
    {
        _ba = await _host.ActorAsync(Roles.BusinessAnalyst);
        _ba2 = await _host.ActorAsync(Roles.BusinessAnalyst);
        _reviewer = await _host.ActorAsync(Roles.Reviewer);
        _dev = await _host.ActorAsync(Roles.Developer);
        _qa = await _host.ActorAsync(Roles.QA);
        _admin = await _host.AdminAsync();
    }

    public Task DisposeAsync() => _host.DisposeAsync().AsTask();

    // ---- helpers ---------------------------------------------------------------------------

    private static int Int(JsonNode? n, string key) => n![key]!.GetValue<int>();
    private static string? Str(JsonNode? n, string key) => n?[key]?.GetValue<string>();

    // Generated by `author` (so they are the NFR's author) in a project every other actor belongs to.
    private async Task<(string ProjectId, JsonNode Generated)> GenerateAsync(Actor author)
    {
        var (ps, project) = await author.Api.PostAsync("/api/projects", new { name = "Leave system", description = "d" });
        Assert.Equal(201, ps);
        var projectId = Id(project);
        foreach (var member in new[] { _ba, _ba2, _reviewer, _dev, _qa }.Where(m => m.Id != author.Id))
        {
            Assert.InRange((await _host.AddMemberAsync(author.Api, projectId, member.Api)).Status, 200, 201);
        }

        var (_, source) = await author.Api.PostAsync($"/api/projects/{projectId}/requirement-sources",
            new { sourceType = 1, rawText = "Employees submit leave requests; managers approve them within two days." });
        var (gs, generated) = await author.Api.PostAsync($"/api/requirement-sources/{Id(source)}/generate-requirements");
        Assert.Equal(200, gs);
        return (projectId, generated!);
    }

    private async Task<string> NfrAsync(Actor? author = null)
    {
        var (_, generated) = await GenerateAsync(author ?? _ba);
        return Id(generated["nonFunctionalRequirements"]![0]);
    }

    private static Task<(int Status, JsonNode? Body)> ConfirmAsync(Actor user, string id, int? version = 1) =>
        user.Api.PostAsync($"/api/artifacts/{id}/nfr-confirmation", new { version });

    private async Task<JsonNode> GetAsync(string id) => (await _ba.Api.GetAsync($"/api/artifacts/{id}")).Body!;

    private static Task<(int Status, JsonNode? Body)> EditAsync(Actor user, string id, object data, string? title = null) =>
        user.Api.SendAsync(HttpMethod.Patch, $"/api/artifacts/{id}", new { title, data, reason = "edit" });

    private static Task<(int Status, JsonNode? Body)> SetStatusAsync(Actor user, string id, int status, string? comment = null) =>
        user.Api.SendAsync(HttpMethod.Patch, $"/api/artifacts/{id}/status", new { status, comment });

    private async Task<string> ConfirmedNfrAsync()
    {
        var nfrId = await NfrAsync();
        Assert.Equal(200, (await ConfirmAsync(_ba2, nfrId)).Status);
        return nfrId;
    }

    // ---- authorization ---------------------------------------------------------------------

    [Fact]
    public async Task A_business_analyst_confirms_another_users_nfr_recording_who_and_when_and_changing_nothing_else()
    {
        var nfrId = await NfrAsync();
        var before = await GetAsync(nfrId);
        Assert.Equal(Proposed, Str(before["data"], "assumptionStatus"));
        var started = DateTime.UtcNow.AddSeconds(-5);

        var (status, confirmed) = await ConfirmAsync(_ba2, nfrId);

        Assert.Equal(200, status);
        var data = confirmed!["data"]!;
        Assert.Equal(Confirmed, Str(data, "assumptionStatus"));
        Assert.Equal(_ba2.Id, Str(data, "confirmedByUserId"));
        var confirmedAt = DateTime.Parse(Str(data, "confirmedAt")!, CultureInfo.InvariantCulture, DateTimeStyles.RoundtripKind).ToUniversalTime();
        Assert.InRange(confirmedAt, started, DateTime.UtcNow.AddSeconds(5));

        // No other NFR field, the title, or the status (unapproved stays unapproved) changed.
        foreach (var field in new[] { "category", "description", "targetValue" })
        {
            Assert.Equal(before["data"]![field]?.ToJsonString(), data[field]?.ToJsonString());
        }
        Assert.Equal(before["title"]!.GetValue<string>(), confirmed["title"]!.GetValue<string>());
        Assert.Equal(AiGenerated, Int(confirmed, "status"));
        Assert.Null(confirmed["approvedVersion"]);

        // Recorded as a new human version by the confirmer; persisted, not just echoed.
        Assert.Equal(2, Int(confirmed, "currentVersion"));
        var v2 = (await _ba.Api.GetAsync($"/api/artifacts/{nfrId}/versions")).Body!.AsArray().Single(v => Int(v, "versionNumber") == 2)!;
        Assert.Equal(_ba2.Id, Str(v2, "changedByUserId"));
        Assert.Equal("NFR target confirmed", Str(v2, "reason"));
        Assert.Equal(1, Int(v2, "origin")); // Human
        Assert.Equal(Confirmed, Str((await GetAsync(nfrId))["data"], "assumptionStatus"));
    }

    [Fact]
    public async Task A_reviewer_confirms_an_approved_nfr_and_it_stays_approved_with_its_approval_history_intact()
    {
        var (projectId, generated) = await GenerateAsync(_ba);
        var nfrId = Id(generated["nonFunctionalRequirements"]![0]);
        Assert.Equal(200, (await SetStatusAsync(_reviewer, nfrId, Approved, "fine")).Status);
        var notices = await _host.ScalarAsync($"SELECT COUNT(*) FROM ArtifactImpactNotices WHERE ProjectId = '{projectId}'");

        var (status, confirmed) = await ConfirmAsync(_reviewer, nfrId);

        Assert.Equal(200, status);
        Assert.Equal(Confirmed, Str(confirmed!["data"], "assumptionStatus"));
        Assert.Equal(_reviewer.Id, Str(confirmed["data"], "confirmedByUserId"));
        Assert.Equal(Approved, Int(confirmed, "status")); // Approved + Confirmed, not UnderReview
        Assert.Equal(1, Int(confirmed, "approvedVersion")); // the version the reviewer actually approved
        Assert.Equal(2, Int(confirmed, "currentVersion"));

        var versions = (await _ba.Api.GetAsync($"/api/artifacts/{nfrId}/versions")).Body!.AsArray();
        Assert.Equal(Approved, Int(versions.Single(v => Int(v, "versionNumber") == 2), "status"));
        Assert.DoesNotContain(versions, v => Str(v, "reason")?.Contains("re-review") == true);

        var reviews = (await _ba.Api.GetAsync($"/api/artifacts/{nfrId}/reviews")).Body!.AsArray();
        var review = Assert.Single(reviews);
        Assert.Equal(0, Int(review, "decision")); // ReviewDecision.Approved, on v1
        Assert.Equal(1, Int(review, "versionNumber"));

        // Not a content change: nothing downstream is flagged.
        Assert.Equal(notices, await _host.ScalarAsync($"SELECT COUNT(*) FROM ArtifactImpactNotices WHERE ProjectId = '{projectId}'"));
    }

    [Fact]
    public async Task Developer_qa_and_administrator_are_forbidden_and_the_nfr_is_unchanged()
    {
        var nfrId = await NfrAsync();

        foreach (var actor in new[] { _dev, _qa, _admin })
        {
            Assert.Equal(403, (await ConfirmAsync(actor, nfrId)).Status);
        }

        var after = await GetAsync(nfrId);
        Assert.Equal(1, Int(after, "currentVersion"));
        Assert.Equal(Proposed, Str(after["data"], "assumptionStatus"));
    }

    [Fact]
    public async Task An_unauthenticated_request_is_rejected()
    {
        var nfrId = await NfrAsync();
        var anonymous = new ApiUser("anonymous", _host.Factory.CreateClient());

        Assert.Equal(401, (await anonymous.PostAsync($"/api/artifacts/{nfrId}/nfr-confirmation", new { version = 1 })).Status);
        Assert.Equal(Proposed, Str((await GetAsync(nfrId))["data"], "assumptionStatus"));
    }

    [Fact]
    public async Task The_author_cannot_confirm_their_own_nfr()
    {
        var nfrId = await NfrAsync(_ba);

        var (status, body) = await ConfirmAsync(_ba, nfrId);

        Assert.Equal(403, status);
        Assert.Contains("authored", Str(body, "detail"));
        Assert.Equal(Proposed, Str((await GetAsync(nfrId))["data"], "assumptionStatus"));
    }

    [Fact]
    public async Task An_author_holding_both_business_analyst_and_reviewer_roles_still_cannot_confirm_their_own_nfr()
    {
        var both = await _host.ActorAsync(Roles.BusinessAnalyst);
        await _host.ExecuteAsync($"INSERT INTO AspNetUserRoles (UserId, RoleId) SELECT '{both.Id}', Id FROM AspNetRoles WHERE Name = '{Roles.Reviewer}'");
        both = both with { Api = await _host.LoginAsync(both.Api.Email, TestHost.UserPassword) }; // token now carries both roles
        Assert.Equal(2, await _host.ScalarAsync($"SELECT COUNT(*) FROM AspNetUserRoles WHERE UserId = '{both.Id}'"));

        var nfrId = await NfrAsync(both);

        Assert.Equal(403, (await ConfirmAsync(both, nfrId)).Status);

        // Another authorized user still can.
        Assert.Equal(200, (await ConfirmAsync(_reviewer, nfrId)).Status);
    }

    [Fact]
    public async Task Someone_who_authored_the_current_version_cannot_confirm_it()
    {
        var nfrId = await NfrAsync();
        var current = (await GetAsync(nfrId))["data"]!;
        Assert.Equal(200, (await EditAsync(_ba2, nfrId, new
        {
            category = Str(current, "category"),
            description = "Reworded by the second analyst",
            targetValue = Str(current, "targetValue")
        })).Status);

        Assert.Equal(403, (await ConfirmAsync(_ba2, nfrId, version: 2)).Status);
        Assert.Equal(200, (await ConfirmAsync(_reviewer, nfrId, version: 2)).Status);
    }

    // ---- validation ------------------------------------------------------------------------

    [Fact]
    public async Task An_nfr_without_a_target_cannot_be_confirmed()
    {
        var nfrId = await NfrAsync();
        var current = (await GetAsync(nfrId))["data"]!;
        Assert.Equal(200, (await EditAsync(_ba, nfrId, new { category = Str(current, "category"), description = "No target yet", targetValue = "  " })).Status);

        var (status, body) = await ConfirmAsync(_ba2, nfrId, version: 2);

        Assert.Equal(400, status);
        Assert.Contains("no target", Str(body, "detail"));
    }

    [Fact]
    public async Task A_non_nfr_artifact_cannot_use_the_confirmation_endpoint()
    {
        var (_, generated) = await GenerateAsync(_ba);
        var frId = Id(generated["functionalRequirements"]![0]);

        var (status, _) = await ConfirmAsync(_ba2, frId);

        Assert.Equal(400, status);
        Assert.Equal(1, Int(await GetAsync(frId), "currentVersion"));
        Assert.Equal(404, (await ConfirmAsync(_ba2, Guid.NewGuid().ToString())).Status);
    }

    [Fact]
    public async Task A_stale_or_missing_version_cannot_be_confirmed()
    {
        var nfrId = await NfrAsync();
        var current = (await GetAsync(nfrId))["data"]!;
        Assert.Equal(200, (await EditAsync(_ba, nfrId, new
        {
            category = Str(current, "category"),
            description = "Superseded wording",
            targetValue = Str(current, "targetValue")
        })).Status);

        Assert.Equal(409, (await ConfirmAsync(_ba2, nfrId, version: 1)).Status); // v1 was superseded by v2
        Assert.Equal(400, (await ConfirmAsync(_ba2, nfrId, version: null)).Status);
        Assert.Equal(Proposed, Str((await GetAsync(nfrId))["data"], "assumptionStatus"));

        Assert.Equal(200, (await ConfirmAsync(_ba2, nfrId, version: 2)).Status);
    }

    [Fact]
    public async Task An_already_confirmed_nfr_cannot_be_confirmed_again()
    {
        var nfrId = await ConfirmedNfrAsync();

        Assert.Equal(409, (await ConfirmAsync(_reviewer, nfrId, version: 2)).Status);
        var after = await GetAsync(nfrId);
        Assert.Equal(2, Int(after, "currentVersion"));
        Assert.Equal(_ba2.Id, Str(after["data"], "confirmedByUserId"));
    }

    [Fact]
    public async Task A_rejected_nfr_cannot_be_confirmed_and_confirmation_never_changes_the_status()
    {
        var nfrId = await NfrAsync();
        Assert.Equal(200, (await SetStatusAsync(_reviewer, nfrId, Rejected, "target is unrealistic")).Status);

        Assert.Equal(409, (await ConfirmAsync(_ba2, nfrId)).Status);
        var after = await GetAsync(nfrId);
        Assert.Equal(Rejected, Int(after, "status"));
        Assert.Equal(Proposed, Str(after["data"], "assumptionStatus"));
    }

    // ---- the edit bypass -------------------------------------------------------------------

    [Fact]
    public async Task A_normal_edit_cannot_set_the_nfr_to_confirmed()
    {
        var nfrId = await NfrAsync();
        var current = (await GetAsync(nfrId))["data"]!;

        var (status, edited) = await EditAsync(_ba2, nfrId, new
        {
            category = Str(current, "category"),
            description = "Edited",
            targetValue = Str(current, "targetValue"),
            assumptionStatus = Confirmed,
            confirmedByUserId = _reviewer.Id,
            confirmedAt = DateTime.UtcNow
        });

        Assert.Equal(200, status);
        Assert.Equal(Proposed, Str(edited!["data"], "assumptionStatus"));
        Assert.Null(edited["data"]!["confirmedByUserId"]);
        Assert.Null(edited["data"]!["confirmedAt"]);
        Assert.Equal("Edited", Str(edited["data"], "description"));
        Assert.Equal(Proposed, Str((await GetAsync(nfrId))["data"], "assumptionStatus"));
    }

    [Fact]
    public async Task Changing_the_target_of_a_confirmed_nfr_resets_it_to_a_proposed_assumption()
    {
        var nfrId = await ConfirmedNfrAsync();
        var current = (await GetAsync(nfrId))["data"]!;

        var (status, edited) = await EditAsync(_ba, nfrId, new
        {
            category = Str(current, "category"),
            description = Str(current, "description"),
            targetValue = "p95 under 500 ms",
            assumptionStatus = Confirmed, // echoed back by a client; ignored
            confirmedByUserId = Str(current, "confirmedByUserId"),
            confirmedAt = Str(current, "confirmedAt")
        });

        Assert.Equal(200, status);
        Assert.Equal("p95 under 500 ms", Str(edited!["data"], "targetValue"));
        Assert.Equal(Proposed, Str(edited["data"], "assumptionStatus"));
        Assert.Null(edited["data"]!["confirmedByUserId"]);
        Assert.Null(edited["data"]!["confirmedAt"]);
    }

    [Fact]
    public async Task Editing_other_fields_of_a_confirmed_nfr_keeps_the_original_confirmation_and_ignores_client_values()
    {
        var nfrId = await ConfirmedNfrAsync();
        var current = (await GetAsync(nfrId))["data"]!;
        var confirmedAt = Str(current, "confirmedAt");

        var (status, edited) = await EditAsync(_ba, nfrId, new
        {
            category = Str(current, "category"),
            description = "Clarified wording only",
            targetValue = "  " + Str(current, "targetValue") + " ", // whitespace is not a target change
            assumptionStatus = Confirmed,
            confirmedByUserId = _ba.Id, // a client cannot re-attribute the confirmation
            confirmedAt = "2000-01-01T00:00:00Z"
        });

        Assert.Equal(200, status);
        Assert.Equal("Clarified wording only", Str(edited!["data"], "description"));
        Assert.Equal(Confirmed, Str(edited["data"], "assumptionStatus"));
        Assert.Equal(_ba2.Id, Str(edited["data"], "confirmedByUserId"));
        Assert.Equal(confirmedAt, Str(edited["data"], "confirmedAt"));
    }

    [Fact]
    public async Task Removing_the_target_clears_the_assumption_status()
    {
        var nfrId = await ConfirmedNfrAsync();
        var current = (await GetAsync(nfrId))["data"]!;

        var (status, edited) = await EditAsync(_ba, nfrId, new
        {
            category = Str(current, "category"),
            description = Str(current, "description"),
            targetValue = (string?)null,
            assumptionStatus = Confirmed
        });

        Assert.Equal(200, status);
        Assert.Null(edited!["data"]!["assumptionStatus"]);
        Assert.Null(edited["data"]!["confirmedByUserId"]);
    }

    [Fact]
    public async Task Editing_an_approved_confirmed_nfr_still_goes_back_to_review()
    {
        var nfrId = await NfrAsync();
        Assert.Equal(200, (await SetStatusAsync(_reviewer, nfrId, Approved, "fine")).Status);
        Assert.Equal(200, (await ConfirmAsync(_ba2, nfrId)).Status);
        var current = (await GetAsync(nfrId))["data"]!;

        var (_, edited) = await EditAsync(_ba, nfrId, new
        {
            category = Str(current, "category"),
            description = "Reworded after approval",
            targetValue = Str(current, "targetValue")
        });

        Assert.Equal(UnderReview, Int(edited, "status"));
        Assert.Equal(1, Int(edited, "approvedVersion"));
    }

    // ---- regression ------------------------------------------------------------------------

    [Fact]
    public async Task Generation_still_marks_every_generated_target_as_a_proposed_assumption()
    {
        var (_, generated) = await GenerateAsync(_ba);
        var nfrs = generated["nonFunctionalRequirements"]!.AsArray();

        Assert.NotEmpty(nfrs);
        Assert.All(nfrs, nfr =>
        {
            var hasTarget = !string.IsNullOrWhiteSpace(Str(nfr!["data"], "targetValue"));
            Assert.Equal(hasTarget ? Proposed : null, Str(nfr["data"], "assumptionStatus"));
            Assert.Null(nfr["data"]!["confirmedByUserId"]);
        });
    }

    [Fact]
    public async Task An_approved_but_unconfirmed_nfr_does_not_block_analysis_and_can_still_be_confirmed()
    {
        var (projectId, _) = await GenerateAsync(_ba);
        await _host.ExecuteAsync(
            $"UPDATE Artifacts SET Status = {Approved}, ApprovedVersion = CurrentVersion WHERE ProjectId = '{projectId}' AND ArtifactType = {(int)ArtifactType.NonFunctionalRequirement}");

        async Task<bool> NfrCheckPassesAsync()
        {
            using var s = _host.As(_ba);
            var analysis = (await s.Evidence.GetAsync(Guid.Parse(projectId))).Single(e => e.Stage == ProjectStatus.Analysis);
            return analysis.Checks.Single(c => c.Label == "Non-functional requirements approved").Passed;
        }

        Assert.True(await NfrCheckPassesAsync());

        var nfrId = Id((await _ba.Api.GetAsync($"/api/projects/{projectId}/artifacts?type={(int)ArtifactType.NonFunctionalRequirement}")).Body!.AsArray()[0]);
        Assert.Equal(Proposed, Str((await GetAsync(nfrId))["data"], "assumptionStatus"));
        Assert.Equal(200, (await ConfirmAsync(_reviewer, nfrId)).Status);
        Assert.True(await NfrCheckPassesAsync());
    }
}
