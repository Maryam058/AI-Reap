// Covers the status-aware test case review guidance (ArtifactCard, WorkRecordPanel). Text only: the
// workflow itself is enforced and tested in AiReap.Tests (ArtifactStatusTransitions, ArtifactWorkService).
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { ARTIFACT_STATUS } from '../src/api/types.ts';
import { testCaseReviewNote, testResultGateMessage } from '../src/lib/testCaseReview.ts';

const { AiGenerated, Draft, UnderReview, Approved, Rejected, Implemented, Verified } = ARTIFACT_STATUS;

test('Draft: submit for review first, then a BA, Reviewer or Administrator approves before QA records', () => {
  assert.equal(
    testResultGateMessage(Draft),
    'This test case is still in Draft. Submit it for review first. A Business Analyst, Reviewer, or Administrator must approve it before QA can record a test result.',
  );
});

test('Under Review: awaiting a BA, Reviewer or Administrator decision', () => {
  assert.equal(
    testResultGateMessage(UnderReview),
    'This test case is awaiting review. A Business Analyst, Reviewer, or Administrator must approve it before QA can record a test result.',
  );
});

test('AI Generated: approved directly, without Submit for review', () => {
  const message = testResultGateMessage(AiGenerated)!;
  assert.match(message, /^This test case was generated by AI and can be approved directly by a Business Analyst, Reviewer, or Administrator/);
  assert.match(message, /without the Submit for review step/);
  assert.match(message, /QA can record the test result after approval\.$/);
});

test('Rejected: resubmit for review before a result can be recorded', () => {
  assert.match(testResultGateMessage(Rejected)!, /submit it for review again/);
});

test('approved or later: no gate message, the result buttons are shown instead', () => {
  for (const status of [Approved, Implemented, Verified]) assert.equal(testResultGateMessage(status), null);
});

test('Draft card note: cannot be approved directly, Submit for review moves it to Under Review, QA cannot approve', () => {
  const note = testCaseReviewNote(Draft)!;
  assert.match(note, /^This test case is still in Draft\. Submit it for review first\. A Business Analyst, Reviewer, or Administrator can then approve or reject it\./);
  assert.match(note, /A Draft cannot be approved directly/);
  assert.match(note, /Submit for review moves it to Under Review/);
  assert.match(note, /QA cannot approve test cases/);
});

test('card note appears only for Draft', () => {
  for (const status of [AiGenerated, UnderReview, Approved, Rejected, Implemented, Verified]) assert.equal(testCaseReviewNote(status), null);
});
