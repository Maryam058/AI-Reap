// Imported with its extension so `node --test` can load this module directly (tests/testCaseReview.test.ts).
import { ARTIFACT_STATUS } from '../api/types.ts';

// Guidance text only. It explains the workflow ArtifactStatusTransitions and ArtifactWorkService already
// enforce - Draft -> Under Review -> Approved/Rejected, AI Generated decided directly, results only on
// an approved test case - and never changes who may do what.

const APPROVERS = 'A Business Analyst, Reviewer, or Administrator';

/** Shown on a Draft test case's card: why Approve/Reject are not offered yet. Null for other statuses. */
export function testCaseReviewNote(status: number): string | null {
  return status === ARTIFACT_STATUS.Draft
    ? `This test case is still in Draft. Submit it for review first. ${APPROVERS} can then approve or reject it. ` +
        'A Draft cannot be approved directly: Submit for review moves it to Under Review. QA cannot approve test cases.'
    : null;
}

/**
 * Why a test result cannot be recorded yet, by the test case's status. Null once it is approved
 * (Approved, Implemented or Verified), when the Test execution panel offers Passed / Failed / Blocked.
 */
export function testResultGateMessage(status: number): string | null {
  switch (status) {
    case ARTIFACT_STATUS.Approved:
    case ARTIFACT_STATUS.Implemented:
    case ARTIFACT_STATUS.Verified:
      return null;
    case ARTIFACT_STATUS.Draft:
      return `This test case is still in Draft. Submit it for review first. ${APPROVERS} must approve it before QA can record a test result.`;
    case ARTIFACT_STATUS.UnderReview:
      return `This test case is awaiting review. ${APPROVERS} must approve it before QA can record a test result.`;
    case ARTIFACT_STATUS.AiGenerated:
      return `This test case was generated by AI and can be approved directly by a Business Analyst, Reviewer, or Administrator, without the Submit for review step. QA can record the test result after approval.`;
    case ARTIFACT_STATUS.Rejected:
      return `This test case was rejected. Update it if needed and submit it for review again. ${APPROVERS} must approve it before QA can record a test result.`;
    default:
      return 'This test case must be approved before a result can be recorded.';
  }
}
